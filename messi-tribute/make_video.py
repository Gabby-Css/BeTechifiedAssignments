# --------------------------------------------------------------------------- background
HW, HH = W // 2, H // 2
_yy = np.linspace(0, 1, HH, dtype=np.float32)[:, None]
_xx = np.linspace(-1, 1, HW, dtype=np.float32)[None, :]
_c0, _c1 = np.array(NAVY0, np.float32), np.array(NAVY1, np.float32)
BASE = _c0 + (_c1 - _c0) * ((1 - _yy) ** 1.4)[..., None]
GLOW = np.exp(-(np.hypot(_xx * 0.95, (_yy - 0.40) * 1.15) / 0.62) ** 2).astype(np.float32)
_rv = np.hypot(_xx, (_yy - 0.5) * 1.8)
VIGN = (1 - 0.60 * np.clip((_rv - 0.45) / 0.9, 0, 1) ** 1.5).astype(np.float32)[..., None]
_PER = 200
_sx = np.arange(HW + _PER, dtype=np.float32)
STRIPE_1D = (0.5 + 0.5 * np.tanh(6 * np.sin(2 * np.pi * _sx / _PER))).astype(np.float32)
_ymask = (np.clip(1.15 - _yy * 1.3, 0, 1) ** 1.2).astype(np.float32)

GOLD_SEGS = [(b(28), b(36)), (b(36), b(40)), (b(56), b(64))]
DRUM_SEGS = [(b(12), b(36)), (b(48), b(56))]


def gold_mix(t):
    m = 0.0
    for a, z in GOLD_SEGS:
        m = max(m, smoothstep(a - 0.3, a + 0.3, t) * (1 - smoothstep(z - 0.3, z + 0.3, t)))
    return m


def pulse(t):
    on = 0.0
    for a, z in DRUM_SEGS:
        on = max(on, 1.0 if a <= t < z else 0.0)
    ph = (t % BEAT) / BEAT
    return math.exp(-ph * 5) * on + 0.25 * math.exp(-ph * 3) * (1 - on)


def make_background(t):
    gm = gold_mix(t)
    col = np.array(SKY, np.float32) * (1 - gm) + np.array(GOLD, np.float32) * gm
    strength = 0.40 + 0.22 * pulse(t) + 0.12 * gm
    off = int(t * 16) % _PER
    stripes = STRIPE_1D[off:off + HW][None, :] * _ymask
    img = BASE + GLOW[..., None] * col * strength
    img += stripes[..., None] * np.array(SKY, np.float32) * 0.07
    img *= VIGN
    im = Image.fromarray(np.clip(img, 0, 255).astype(np.uint8), "RGB").resize((W, H), Image.Resampling.BILINEAR)
    return im.convert("RGBA")


