# --------------------------------------------------------------------------- easing
clamp = lambda x, lo=0.0, hi=1.0: lo if x < lo else hi if x > hi else x


def ease_out_cubic(p): return 1 - (1 - p) ** 3
def ease_out_quart(p): return 1 - (1 - p) ** 4
def ease_out_expo(p): return 1.0 if p >= 1 else 1 - 2 ** (-10 * p)


def ease_out_back(p, s=1.9):
    p -= 1
    return 1 + (s + 1) * p ** 3 + s * p ** 2


def smoothstep(a, b_, x):
    p = clamp((x - a) / (b_ - a))
    return p * p * (3 - 2 * p)


