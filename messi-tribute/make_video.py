def prepare_footage(clips_dir: str, work: str) -> str:
    files = sorted(f for f in os.listdir(clips_dir) if os.path.splitext(f)[1].lower() in VIDEO_EXT | IMAGE_EXT)
    if not files:
        raise SystemExit(f"--clips: no videos/images found in {clips_dir}")
    print(f"[footage] {len(files)} file(s), cutting one per bar ({BAR:.2f}s each)")
    segs = []
    nfr = round(BAR * FPS)
    for bar in range(BARS):
        src = os.path.join(clips_dir, files[bar % len(files)])
        seg = os.path.join(work, f"seg_{bar:02d}.mp4")
        if os.path.splitext(src)[1].lower() in IMAGE_EXT:
            cmd = ["ffmpeg", "-y", "-loglevel", "error", "-i", src, "-vf",
                   "scale=2160:3840:force_original_aspect_ratio=increase,crop=2160:3840,"
                   f"zoompan=z='min(1.0+0.0008*on,1.25)':x='iw/2-(iw/zoom/2)':y='ih/2-(ih/zoom/2)':d={nfr}:s=1080x1920:fps={FPS}",
                   "-frames:v", str(nfr), "-pix_fmt", "yuv420p", "-c:v", "libx264", "-crf", "14", seg]
        else:
            cmd = ["ffmpeg", "-y", "-loglevel", "error", "-stream_loop", "-1", "-i", src, "-t", f"{BAR:.3f}",
                   "-vf", f"scale=1080:1920:force_original_aspect_ratio=increase,crop=1080:1920,fps={FPS}",
                   "-an", "-pix_fmt", "yuv420p", "-c:v", "libx264", "-crf", "14", seg]
        subprocess.run(cmd, check=True)
        segs.append(seg)
    lst = os.path.join(work, "list.txt")
    with open(lst, "w") as fh:
        fh.writelines(f"file '{s}'\n" for s in segs)
    bg = os.path.join(work, "bg.mp4")
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-f", "concat", "-safe", "0", "-i", lst,
                    "-c", "copy", bg], check=True)
    frames = os.path.join(work, "frames")
    os.makedirs(frames, exist_ok=True)
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", bg, "-frames:v", str(NFRAMES), "-q:v", "3",
                    os.path.join(frames, "bg_%05d.jpg")], check=True)
    return frames


# --------------------------------------------------------------------------- audio (all synthesized)
def mtof(m): return 440.0 * 2 ** ((m - 69) / 12)


def fft_filter(x, lo=None, hi=None):
    X = np.fft.rfft(x)
    f = np.fft.rfftfreq(len(x), 1 / SR)
    if hi:
        X *= 1 / (1 + (f / hi) ** 4)
    if lo:
        X *= 1 - 1 / (1 + (f / lo) ** 4)
    return np.fft.irfft(X, len(x))


def fft_conv(x, ir):
    n = len(x) + len(ir) - 1
    nfft = 1 << (n - 1).bit_length()
    return np.fft.irfft(np.fft.rfft(x, nfft) * np.fft.rfft(ir, nfft), nfft)[:n]


def reverb(x, seed, rt=2.4):
    n = int(rt * SR)
    r = np.random.default_rng(seed)
    ir = r.standard_normal(n) * np.exp(-np.arange(n) / SR * (6.9 / rt))
    ir = fft_filter(ir, hi=4500)
    ir = np.concatenate([np.zeros(int(0.02 * SR)), ir])
    ir /= np.sqrt(np.sum(ir ** 2))
    return fft_conv(x, ir)[: len(x)]


def pluck(f, dur, vel=1.0, bright=1.0, decay=1.5):
    n = int(dur * SR)
    t = np.arange(n) / SR
    out = np.zeros(n)
    for k in range(1, 10):
        fk = f * k * math.sqrt(1 + 0.0003 * k * k)
        if fk > SR / 2.3:
            break
        out += vel / k ** (1.25 / bright) * np.sin(2 * np.pi * fk * t) * np.exp(-t * (decay + 0.8 * k))
    return out * np.minimum(1, t / 0.004)


def pad_voice(freqs, dur, seed=1):
    n = int(dur * SR)
    t = np.arange(n) / SR
    r = np.random.default_rng(seed)
    out = np.zeros(n)
    for f in freqs:
        for det in (-0.004, 0.0, 0.004):
            ff = f * (1 + det)
            ph = r.uniform(0, 6.28)
            for k in range(1, 7):
                out += np.sin(2 * np.pi * k * ff * t + ph) / k ** 1.7
    env = np.minimum(1, t / 1.0) * np.minimum(1, np.maximum(0, (dur - t)) / 1.0)
    return out * env


def sub_note(f, dur):
    t = np.arange(int(dur * SR)) / SR
    env = np.minimum(1, t / 0.05) * np.minimum(1, (dur - t) / 0.2)
    return (np.sin(2 * np.pi * f * t) + 0.25 * np.sin(2 * np.pi * 2 * f * t)) * env


def kick():
    n = int(0.5 * SR)
    t = np.arange(n) / SR
    f = 42 + 140 * np.exp(-t * 30)
    y = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 6.0)
    y += np.random.default_rng(1).standard_normal(n) * np.exp(-t * 250) * 0.25
    return y


def clap():
    n = int(0.35 * SR)
    t = np.arange(n) / SR
    r = np.random.default_rng(2)
    y = np.zeros(n)
    for d in (0, 0.009, 0.019):
        s = int(d * SR)
        y[s:] += r.standard_normal(n - s) * np.exp(-t[: n - s] * (60 if d < 0.019 else 17))
    y = fft_filter(y, lo=1200, hi=7500)
    return y * 0.55


def hat(open_=False):
    n = int((0.22 if open_ else 0.07) * SR)
    t = np.arange(n) / SR
    y = np.random.default_rng(3).standard_normal(n) * np.exp(-t * (18 if open_ else 70))
    return fft_filter(y, lo=7000) * 0.35


def boom(strength):
    n = int(1.6 * SR)
    t = np.arange(n) / SR
    f = 38 + 70 * np.exp(-t * 7)
    y = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 3.0)
    nz = fft_filter(np.random.default_rng(4).standard_normal(n), hi=1800) * np.exp(-t * 4.5) * 0.5
    return (y + nz) * strength


def riser(dur):
    n = int(dur * SR)
    t = np.arange(n) / SR
    p = t / dur
    nz = np.random.default_rng(5).standard_normal(n)
    nz = np.diff(nz, prepend=0)
    sw = np.sin(2 * np.pi * np.cumsum(200 + 1800 * p ** 2) / SR) * 0.25
    return (nz * 0.5 + sw) * p ** 2.2


def tick():
    n = int(0.02 * SR)
    t = np.arange(n) / SR
    return np.sin(2 * np.pi * 2400 * t) * np.exp(-t * 220) * 0.5


def synth_score(path: str):
    N = int(DUR * SR)
    PAN = lambda p: (math.cos((p + 1) * math.pi / 4), math.sin((p + 1) * math.pi / 4))

    def add(buf, start, sig, gain=1.0, pan=0.0):
        i = int(start * SR)
        if i < 0:                      # note starts before t=0 (pad swell into bar 0)
            sig, i = sig[-i:], 0
        if i >= N or len(sig) == 0:
            return
        sig = sig[: N - i]
        gl, gr = PAN(pan)
        buf[0, i:i + len(sig)] += sig * gain * gl
        buf[1, i:i + len(sig)] += sig * gain * gr

    musical = np.zeros((2, N))   # goes through the reverb
    dry = np.zeros((2, N))       # drums, impacts
    sub = np.zeros((2, N))
    duck = np.ones(N)

    prog = [0, 1, 2, 3] * 4
    prog[14], prog[15] = 1, 0                                   # end on  F -> Am
    chords = {0: (45, [57, 60, 64, 69]), 1: (41, [53, 57, 60, 65]),
              2: (48, [55, 60, 64, 67]), 3: (43, [55, 59, 62, 67])}
    melody = {0: [(76, 0, 1.5), (74, 1.5, .5), (72, 2, 1), (69, 3, 1)],
              1: [(72, 0, 1.5), (69, 1.5, .5), (65, 2, 1), (69, 3, 1)],
              2: [(67, 0, 1), (72, 1, 1), (76, 2, 2)],
              3: [(74, 0, 1.5), (71, 1.5, .5), (67, 2, 2)]}
    arp_pat = [0, 1, 2, 3, 2, 1, 2, 3]

    for bar in range(BARS):
        t0 = bar * BAR
        root, notes = chords[prog[bar]]
        breakdown = 9 <= bar <= 11
        drums = 3 <= bar <= 8 or 12 <= bar <= 13
        # sub bass + pad
        add(sub, t0, sub_note(mtof(root - 12), BAR + 0.1),
            gain=0.0 if breakdown else (0.22 if drums else 0.13))
        add(musical, t0 - 0.2, pad_voice([mtof(n_ - 12) for n_ in notes[:3]], BAR + 0.5, seed=bar),
            gain=(0.030 if breakdown else 0.045 if drums else 0.036))
        # arpeggio (piano)
        if not breakdown and bar < 14:
            vel = 0.5 if bar < 3 else 0.7
            for s in range(8):
                nt = notes[arp_pat[s]] + (12 if s % 8 == 7 and bar > 11 else 0)
                add(musical, t0 + s * BEAT / 2, pluck(mtof(nt), 2.2, vel * (0.8 + 0.2 * (s % 2 == 0))),
                    gain=0.20, pan=-0.25 if s % 2 else 0.25)
        elif breakdown:                                           # slower, warmer, broken chords
            for s, idx in enumerate([0, 2, 1, 3]):
                add(musical, t0 + s * BEAT, pluck(mtof(notes[idx] - 12 * (s == 0)), 3.0, 0.9, 0.8, 1.1),
                    gain=0.26, pan=-0.15)
        else:                                                     # final bars: whole-note chord
            for nt in notes:
                add(musical, t0, pluck(mtof(nt), 4.0, 0.8, 0.8, 0.9), gain=0.20)
        # melody
        if breakdown or bar >= 14 or 12 <= bar <= 13:
            for m_, st, du in melody[prog[bar]]:
                add(musical, t0 + st * BEAT, pluck(mtof(m_), 3.2, 1.0, 1.3, 0.9),
                    gain=0.26 if breakdown or bar >= 14 else 0.15, pan=0.1)
        # drums
        if drums:
            kk, cl = kick(), clap()
            hits = [0, 2, 3.75] if bar % 2 == 0 else [0, 2, 2.75]
            for bt in hits:
                add(dry, t0 + bt * BEAT, kk, gain=0.9 if bt in (0, 2) else 0.6)
                i = int((t0 + bt * BEAT) * SR)
                L = int(0.28 * SR)
                if i < N:
                    seg = np.arange(min(L, N - i)) / SR
                    duck[i:i + len(seg)] *= 1 - 0.5 * np.exp(-seg / 0.11)
            for bt in (1, 3):
                add(dry, t0 + bt * BEAT, cl, gain=0.8)
            for s in range(8):
                add(dry, t0 + s * BEAT / 2, hat(s == 7), gain=0.5 + 0.25 * (s % 2 == 1), pan=0.3)

    # impacts, risers, ticks, chimes
    for bt, s in HIT_TIMES:
        add(dry, bt, boom(s), gain=0.40 * (0.6 if 36 <= bt / BEAT < 48 else 1.0))
    for end_beat, length in [(4, 4), (10, 2), (12, 4), (40, 2), (48, 4), (53, 2), (59, 2)]:
        d = length * BEAT
        add(dry, b(end_beat) - d, riser(d), gain=0.20)
    # year-ticker clicks follow the same easing as the video
    prev = 2005
    for k in range(int(1.75 * BEAT * FPS) + 1):
        tt = k / FPS
        v = 2005 + int(21 * ease_out_quart(clamp(tt / (b(1.75)))) + 0.5)
        if v != prev:
            add(dry, b(8.25) + tt, tick(), gain=0.5)
            prev = v
    for k, (mid, dt_) in enumerate([(88, 56), (91, 56.5), (95, 57)]):
        add(musical, b(dt_), pluck(mtof(mid), 2.5, 0.8, 1.6, 1.6), gain=0.16, pan=(-0.4, 0, 0.4)[k])
    # roll-up ticks for the stat counters
    for k in range(4):
        n_ = (208, 126, 70, 6)[k]
        prev = 0
        for f_ in range(int(b(2) * FPS) + 1):
            v = int(n_ * ease_out_quart(clamp(f_ / FPS / b(2))) + 0.5)
            if v != prev:
                add(dry, b(12 + 4 * k) + f_ / FPS, tick(), gain=0.25)
                prev = v

    # level automation: sparse hook, full drops, intimate breakdown for the farewell, soft landing
    bar_level = [0.50, 0.55, 0.65, 1, 1, 1, 1, 1, 1, 0.55, 0.60, 0.70, 1, 1, 0.85, 0.65]
    tt = np.arange(N) / SR
    env = np.array(bar_level)[np.minimum((tt / BAR).astype(int), BARS - 1)]
    k = int(0.45 * SR)
    env = np.convolve(np.pad(env, (k, k), mode="edge"), np.ones(k) / k, mode="same")[k:-k]
    musical = np.stack([fft_filter(musical[0], lo=90), fft_filter(musical[1], lo=90)])

    # mix:  musical -> sidechain + reverb ; sub ducked ; dry as is
    musical *= duck * env
    sub *= duck * env
    wet = np.stack([reverb(musical[0], 11), reverb(musical[1], 12)])
    mix = musical * 0.8 + wet * 0.55 + sub + dry
    mix = np.tanh(mix * 1.4) / np.tanh(1.4)
    fade = np.minimum(1, np.arange(N) / (0.04 * SR)) * np.minimum(1, (N - np.arange(N)) / (1.2 * SR))
    mix *= fade
    mix *= 0.89 / np.max(np.abs(mix))
    pcm = (mix.T * 32767).astype("<i2")
    with wave.open(path, "wb") as w:
        w.setnchannels(2)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    print(f"[audio] wrote {path}  ({N / SR:.2f}s)")


