@lru_cache(maxsize=None)
def font_path(kind: str) -> str:
    for p in FONT_CANDIDATES[kind]:
        if os.path.exists(p):
            return p
    raise SystemExit("No usable bold font found - install Inter (free, SIL OFL) or edit FONT_CANDIDATES.")


@lru_cache(maxsize=None)
def font(kind: str, size: int) -> ImageFont.FreeTypeFont:
    return ImageFont.truetype(font_path(kind), size)


def with_glow(main, mask, color, radius, boost=1.45):
    """Soft glow = SOLID colour with a blurred alpha mask (blurring RGBA directly leaves a dark halo)."""
    a = mask.filter(ImageFilter.GaussianBlur(radius)).point(lambda v: min(255, int(v * boost)))
    g = Image.new("RGBA", main.size, tuple(color) + (0,))
    g.putalpha(a)
    g.alpha_composite(main)
    return g


Sprite = namedtuple("Sprite", "img ax ay")


def text_width_at_100(text, kind, tracking):
    f = font(kind, 100)
    if tracking:
        return sum(f.getlength(ch) for ch in text) + tracking * 100 * (len(text) - 1)
    l, _, r, _ = f.getbbox(text, anchor="ls")
    return r - l


def fit_size(text, kind, size, max_w, tracking):
    w100 = text_width_at_100(text, kind, tracking)
    return max(8, min(size, int(max_w / w100 * 100)))


@lru_cache(maxsize=1024)
def text_sprite(text, kind, size, color, tracking_em, glow, glow_color):
    f = font(kind, size)
    cap_h = -f.getbbox("H", anchor="ls")[1]
    desc = int(size * 0.28)
    over = int(size * 0.06)
    pad = int(glow * 3) + 12
    tr = tracking_em * size
    if tr:
        adv = [f.getlength(ch) for ch in text]
        l, r = 0, sum(adv) + tr * (len(text) - 1)
    else:
        l, _, r, _ = f.getbbox(text, anchor="ls")
    wl = int(math.ceil(r - l)) + 2 * pad
    base_y = pad + over + cap_h
    hl = base_y + desc + pad

    def paint(col):
        layer = Image.new("RGBA", (wl, hl), (0, 0, 0, 0))
        d = ImageDraw.Draw(layer)
        if tr:
            x = pad
            for ch, a in zip(text, adv):
                d.text((x, base_y), ch, font=f, fill=col, anchor="ls")
                x += a + tr
        else:
            d.text((pad - l, base_y), text, font=f, fill=col, anchor="ls")
        return layer

    main = paint(color)
    if glow:
        main = with_glow(main, paint(glow_color or color).getchannel("A"), glow_color or color, glow)
    return Sprite(main, wl / 2, base_y - cap_h / 2)


@lru_cache(maxsize=64)
def star_sprite(size, glow=22):
    pad = glow * 3
    s = size + 2 * pad
    pts = []
    for k in range(10):
        ang = -math.pi / 2 + k * math.pi / 5
        r = size / 2 * (1.0 if k % 2 == 0 else 0.42)
        pts.append((s / 2 + r * math.cos(ang), s / 2 + r * math.sin(ang)))
    layer = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    ImageDraw.Draw(layer).polygon(pts, fill=GOLD + (255,))
    g = with_glow(layer, layer.getchannel("A"), GOLD, glow)
    return Sprite(g, s / 2, s / 2)


@lru_cache(maxsize=64)
def dot_sprite(size, color, alpha_q):
    s = size * 3
    yy, xx = np.mgrid[0:s, 0:s].astype(np.float32)
    r = np.hypot(xx - s / 2, yy - s / 2) / (s / 2)
    a = np.clip(1 - r, 0, 1) ** 2.2 * (alpha_q / 10.0) * 255
    arr = np.zeros((s, s, 4), np.uint8)
    arr[..., 0], arr[..., 1], arr[..., 2] = color
    arr[..., 3] = a.astype(np.uint8)
    return Image.fromarray(arr, "RGBA")


# --------------------------------------------------------------------------- scene helper
def hit_state(t):
    """(flash, shake_x, shake_y) from the most recent hit."""
    flash = sx = sy = 0.0
    for ht, s in HIT_TIMES:
        dt = t - ht
        if 0 <= dt < 0.5:
            if s >= 0.95:
                flash = max(flash, 0.5 * math.exp(-dt * 13))
            amp = 20 * s * math.exp(-dt * 10)
            sx += amp * math.sin(dt * 95)
            sy += amp * 0.7 * math.cos(dt * 79)
    return flash, sx, sy


class Ctx:
    def __init__(self, canvas, t, sx, sy):
        self.canvas, self.t, self.sx, self.sy = canvas, t, sx, sy

    # -- low level
    def blit(self, sp: Sprite, cx, cy, scale=1.0, alpha=1.0, shake=True):
        if alpha <= 0.003:
            return
        img = sp.img
        if abs(scale - 1) > 0.004:
            img = img.resize((max(1, int(img.width * scale)), max(1, int(img.height * scale))),
                             Image.Resampling.BICUBIC)
        if alpha < 0.995:
            img = img.copy()
            img.putalpha(img.getchannel("A").point(lambda v: int(v * alpha)))
        x = int(cx - sp.ax * scale + (self.sx if shake else 0))
        y = int(cy - sp.ay * scale + (self.sy if shake else 0))
        # crop to canvas bounds (alpha_composite refuses negative destinations)
        l, t_ = max(0, -x), max(0, -y)
        r, bt = min(img.width, W - x), min(img.height, H - y)
        if r <= l or bt <= t_:
            return
        self.canvas.alpha_composite(img.crop((l, t_, r, bt)), (x + l, y + t_))

    def _exit(self, t1):
        if t1 is None:
            return 1.0
        return clamp((t1 - self.t) / 0.22)

    # -- text
    def el(self, text, cx, cy, size, t0, t1=None, color=WHITE, kind="black", anim="slam",
           tracking=0.0, glow=0, glow_color=None, max_w=900, ghost=True, push=0.04, alpha=1.0):
        dt = self.t - t0
        if dt < 0 or (t1 is not None and self.t >= t1):
            return
        size = fit_size(text, kind, size, max_w, tracking)
        sp = text_sprite(text, kind, size, color, tracking, glow, glow_color)
        a, sc, oy = alpha, 1.0, 0.0
        if anim == "slam":
            sc = 1 + 1.1 * (1 - ease_out_expo(clamp(dt / 0.20)))
            a *= clamp(dt / 0.07)
            sc *= 1 + push * clamp(dt / 2.0)
        elif anim == "rise":
            oy = 60 * (1 - ease_out_cubic(clamp(dt / 0.55)))
            a *= clamp(dt / 0.45)
            sc *= 1 + push * clamp(dt / 2.0)
        elif anim == "pop":
            sc = max(0.01, ease_out_back(clamp(dt / 0.38)))
            a *= clamp(dt / 0.1)
        elif anim == "fade":
            a *= clamp(dt / 0.6)
        xo = self._exit(t1)
        a *= xo
        sc *= 1 + 0.10 * (1 - xo)
        if anim == "slam" and ghost and dt < 0.28:
            k = (1 - dt / 0.28) ** 2
            off = 30 * k
            for col, sgn in ((SKY, -1), (GOLD, 1)):
                gs = text_sprite(text, kind, size, col, tracking, 0, None)
                self.blit(gs, cx + sgn * off, cy, sc, a * 0.55 * k)
        self.blit(sp, cx, cy + oy, sc, a)

    def counter(self, target, cx, cy, size, t0, dur, t1=None, color=WHITE, start=0,
                glow=0, glow_color=None, max_w=900):
        dt = self.t - t0
        if dt < 0 or (t1 is not None and self.t >= t1):
            return
        cell100 = max(font("black", 100).getlength(str(d)) for d in range(10))
        size = max(8, min(size, int(max_w / (cell100 * len(str(target))) * 100)))
        cell = cell100 * size / 100
        e = ease_out_quart(clamp(dt / dur))
        val = start + int((target - start) * e + 0.5)
        s = str(val)
        n = len(s)
        a = clamp(dt / 0.12)
        sc = 1.0
        if dt > dur:
            q = clamp((dt - dur) / 0.30)
            sc = 1 + 0.10 * (1 - ease_out_cubic(q))
        xo = self._exit(t1)
        a *= xo
        sc *= 1 + 0.10 * (1 - xo)
        total = cell * n
        for j, ch in enumerate(s):
            if ch == " ":
                continue
            sp = text_sprite(ch, "black", size, color, 0.0, glow, glow_color)
            x = cx + (-total / 2 + (j + 0.5) * cell) * sc
            if dt > dur and dt - dur < 0.28:
                k = (1 - (dt - dur) / 0.28) ** 2
                for col, sgn in ((SKY, -1), (GOLD, 1)):
                    gs = text_sprite(ch, "black", size, col, 0.0, 0, None)
                    self.blit(gs, x + sgn * 26 * k, cy, sc, a * 0.5 * k)
            self.blit(sp, x, cy, sc, a)

    def star(self, cx, cy, size, t0, t1=None):
        dt = self.t - t0
        if dt < 0 or (t1 is not None and self.t >= t1):
            return
        sc = max(0.01, ease_out_back(clamp(dt / 0.45)))
        a = clamp(dt / 0.12) * self._exit(t1)
        twinkle = 1 + 0.04 * math.sin(self.t * 4 + cx)
        self.blit(star_sprite(size), cx, cy, sc * twinkle, a)

    def line(self, cx, cy, width, t0, t1=None, color=GOLD, thick=8):
        dt = self.t - t0
        if dt < 0 or (t1 is not None and self.t >= t1):
            return
        w = max(2, int(width * ease_out_cubic(clamp(dt / 0.55))))
        pad = 24
        layer = Image.new("RGBA", (w + 2 * pad, thick + 2 * pad), (0, 0, 0, 0))
        ImageDraw.Draw(layer).rounded_rectangle((pad, pad, pad + w, pad + thick), radius=thick // 2,
                                                fill=color + (255,))
        g = with_glow(layer, layer.getchannel("A"), color, 8)
        self.blit(Sprite(g, g.width / 2, g.height / 2), cx, cy, 1.0, self._exit(t1))


